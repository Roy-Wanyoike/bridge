test('determinism: reversed input arrays produce identical output', () => {
  const reversed = {
    ...ir,
    types: [...ir.types].reverse(),
    services: [...ir.services].reverse(),
    events: [...ir.events].reverse(),
  };
  for (const language of ['go', 'rust', 'typescript', 'python'] as const) {
    const a = generate(ir, { language });
    const b = generate(reversed, { language });
    assert.deepEqual(
      a,
      b,
      `reversed input order changed output for ${language}`,
    );
  }
});

test('options: services and events can be disabled', () => {
  const minimal = makeMinimalIR();
  const py = generate(minimal, { language: 'python' });
  assert.ok(!py.some((f) => f.path.includes('services') || f.path.includes('events')));
  const ts = generate(minimal, { language: 'typescript' });
  assert.ok(!ts.some((f) => f.path.endsWith('services.ts') || f.path.endsWith('events.ts')));
  const go = generate(minimal, { language: 'go' });
  assert.ok(!go.some((f) => f.path === 'services.go' || f.path === 'events.go'));
  const rust = generate(minimal, { language: 'rust' });
  assert.ok(!rust.some((f) => f.path.endsWith('services.rs') || f.path.endsWith('events.rs')));
});

