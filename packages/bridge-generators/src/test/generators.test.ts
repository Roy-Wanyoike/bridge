test('Python: generated code parses with ast.parse and round-trips functionally', () => {
  const files = generate(ir, { language: 'python' });
  const dir = mkdtempSync(join(tmpdir(), 'bridge-pygen-'));
  try {
    for (const file of files) {
      const target = join(dir, file.path);
      execFileSync('mkdir', ['-p', join(dir, 'payments_v1')]);
      // Write with the module layout preserved
      const fsWrite = (p: string, c: string) => require('node:fs').writeFileSync(p, c);
      fsWrite(target, file.content);
    }
    // Syntax check every module
    for (const file of files) {
      if (!file.path.endsWith('.py')) continue;
      execFileSync('python3', [
        '-c', 'import ast,sys; ast.parse(open(sys.argv[1]).read())', join(dir, file.path),
      ]);
    }
    // Functional round-trip inside the generated package
    const script = `
import sys
sys.path.insert(0, ${JSON.stringify(dir)})
import payments_v1 as m
money = m.Money(amount="10.00", currency="USD")
assert m.Money.from_dict(money.to_dict()) == money
order = m.Order(
    order_id="123e4567-e89b-12d3-a456-426614174000", version=1,
    status=m.Status.CAPTURED, amount=m.Money(amount="5.00", currency="EUR"),
    lines=[], created_at="2026-01-01T00:00:00Z", tags={"a","b"}, metadata={"x":"1"})
assert m.Order.from_dict(order.to_dict()) == order
assert order.to_dict()["tags"] == ["a","b"]  # set -> sorted JSON array
assert len(m.validate_Money(m.Money(amount="abc", currency="US"))) == 2
r = m.Resolution.refund(money)
assert m.Resolution.from_dict(r.to_dict()) == r
ev = m.PaymentFailed(payment_id="123e4567-e89b-12d3-a456-426614174000", reason="declined")
name, _ = m.decode_event(m.wrap_payment_failed(ev))
assert name == "PaymentFailed"
assert m.unwrap_payment_failed(m.wrap_payment_failed(ev)) == ev
print("PY-OK")
`;
    const out = execFileSync('python3', ['-c', script]).toString().trim();
    assert.equal(out, 'PY-OK');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('TypeScript: generated code transpiles with zero errors', () => {
  // typescript is available as a devDependency of the monorepo
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const ts = require('typescript') as typeof import('typescript');
  const files = generate(ir, { language: 'typescript' });
  for (const file of files) {
    if (!file.path.endsWith('.ts')) continue;
    const result = ts.transpileModule(file.content, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, strict: true },
      reportDiagnostics: true,
      fileName: file.path,
    });
    const errors = (result.diagnostics ?? []).filter(
      (d) => d.category === ts.DiagnosticCategory.Error,
    );
    assert.equal(
      errors.length,
      0,
      `${file.path}: ${errors
        .map((d) => ts.flattenDiagnosticMessageText(d.messageText, ' '))
        .join('; ')}`,
    );
  }
});

test('Go: braces balance in every file', () => {
  const files = generate(ir, { language: 'go' });
  for (const file of files) {
    if (!file.path.endsWith('.go')) continue;
    let balance = 0;
    for (const ch of file.content) {
      if (ch === '{') balance++;
      if (ch === '}') balance--;
    }
    assert.equal(balance, 0, `${file.path} has unbalanced braces`);
  }
});

